-- More chains: around 50 UK chains with their core dishes, so every branch from
-- the FSA import gets a starting menu. Lists cover each chain's well-known
-- dishes rather than the full menu, and have no prices; diners add the rest.
--
-- Chain menus now live in their own table instead of on template restaurants.

create table public.chain_dishes (
  chain_slug text not null,
  section text,
  name text not null,
  price_pence integer,
  primary key (chain_slug, name)
);
alter table public.chain_dishes enable row level security;

-- The original 8 chains' menus, from their template restaurants in seed.sql.
insert into public.chain_dishes (chain_slug, section, name, price_pence)
select t.chain_slug, d.section, d.name, d.price_pence
from public.restaurants t
join public.dishes d on d.restaurant_id = t.id and d.source = 'chain'
where t.fsa_id is null and t.chain_slug is not null
on conflict do nothing;

